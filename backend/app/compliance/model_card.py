"""docs/MODEL_CARD.md, generated from the code and data so it cannot drift: prompt versions, the shipped role
packs, grading parameters and the integrity signals. Regenerate with `python -m app.cli model-card`; a unit test
fails while the committed card is stale."""

from __future__ import annotations

from pathlib import Path
from typing import get_args

from app.agents import composer
from app.interviews.grading import VARIANCE_POINTS
from app.interviews.integrity import BrowserKind
from app.interviews.schemas import InterviewSettings
from app.rolepacks.service import system_specs

HEADER = "<!-- Generated by `python -m app.cli model-card`. Do not edit by hand. -->"

INTENDED_USE = """\
## Intended use

Intrv-embed conducts structured first-round technical interviews (text or voice) and drafts an
**advisory** scorecard for a human hiring decision. A person reviews every report, can see the evidence
behind each score, and records the decision; the platform never rejects or advances a candidate on its own.

**Out of scope:** automatic hiring decisions, ranking candidates without human review, assessing
personality, emotion, honesty or "culture fit", and any use where a candidate has not been told that an AI
interviews them.
"""

NOT_DONE = """\
## What the system never does

- No emotion, facial-expression, voice-stress, deception or "confidence" analysis (EU AI Act Art. 5(1)(f)).
- No face recognition, identity verification, or age, gender or ethnicity inference (Art. 5(1)(g)).
- Candidate names and demographic details are removed before grading (blind graders).
- Integrity signals (below) go to the human reviewer only. Graders never see them and they never change a score.

`tests/test_banned_imports.py` fails the build if a face, emotion or biometric library enters the backend.
"""

LIMITATIONS = """\
## Known limitations

- Scores depend on the language model the organisation configures. Small local models are weaker at
  structured grading; the report says when grading fell back or failed, and offers "Grade again".
- Speech-to-text errors (accents, noisy rooms, technical vocabulary) can distort voice transcripts. The
  transcript is shown next to every quote so reviewers can check it.
- The rubric measures what the candidate said in this interview, not on-the-job performance.
- Practical-round results depend on the code runner and the vision model being configured; tasks that cannot
  be assessed are skipped and noted in the plan instead of being scored.
- Bias: the platform stores no demographic data, so it cannot measure group outcomes itself. Organisations
  should run an adverse-impact analysis with self-reported data collected outside the platform.
"""


def _prompts() -> list[str]:
    rows = ["| Prompt | Version | Layer |", "|---|---|---|"]
    for path in sorted(composer.PROMPTS_DIR.glob("*.md")):
        prompt = composer.load(path.stem)
        layer = "L0 (platform, never editable)" if path.stem == composer.L0 else "task"
        rows.append(f"| `{path.stem}` | {prompt.version} | {layer} |")
    return rows


def _packs(directory: str) -> list[str]:
    rows: list[str] = []
    for spec in system_specs(directory).values():
        rows.append(f"### {spec.name} (`{spec.slug}` v{spec.version})")
        rows.append("")
        rows.append(f"- Variants: {', '.join(f'{r.name} (`{r.id}`)' for r in spec.roles)}")
        rows.append(f"- Competencies ({len(spec.competencies)}), each with a 4-level behavioural anchor scale:")
        rows.extend(f"  - `{c.id}`: {c.name}" for c in spec.competencies)
        rows.append(f"- Practical tasks: {', '.join(f'`{t.id}`' for t in spec.practical_tasks) or 'none'}")
        rows.append("")
    return rows


def render(role_packs_dir: str) -> str:
    runs = InterviewSettings().grading_runs
    grading = f"""\
## How scores are produced

1. A planner turns the role pack (and the CV, when given) into a topic plan; if no model answers, the plan is
   built from the role pack alone.
2. After the interview, each topic is graded against the competency's anchors by a blind grader, {runs} times by
   default (`grading_runs`). Every score must quote the candidate verbatim; quotes that do not appear in the
   transcript are dropped.
3. The median of the runs is used. A spread of {VARIANCE_POINTS:g} points or more between runs flags the
   competency for human review.
4. Practical submissions are checked by running the candidate's code against the task's tests; the reviewer's
   claims about which known bugs were found are verified against the submission before graders see them.
5. A short narrative is written from the scores. The report is labelled advisory.
"""
    integrity = "\n".join(f"- `{kind}`" for kind in get_args(BrowserKind))
    parts = [
        HEADER,
        "# Model card: Intrv-embed AI interviewer",
        "",
        INTENDED_USE,
        NOT_DONE,
        grading,
        "## Integrity signals (shown to reviewers, never scored)",
        "",
        "Camera signals are computed in the candidate's browser, only with consent, and only as face count and "
        "gaze direction (ADR 0005).",
        "",
        integrity,
        "",
        LIMITATIONS,
        "## Prompts",
        "",
        *_prompts(),
        "",
        "## Shipped role packs",
        "",
        *_packs(role_packs_dir),
    ]
    return "\n".join(parts).rstrip() + "\n"


def write(role_packs_dir: str, out: Path) -> None:
    out.write_text(render(role_packs_dir), encoding="utf-8")
