# Effective permission of the current user (app.org_id / app.user_id / app.role) on every space:
# own personal spaces and (for owners) all org spaces are CONTRIBUTE; grants to the user or to one of
# their groups give READ or CONTRIBUTE until they expire.
SPACE_PERMISSIONS = f"""
CREATE FUNCTION app_space_permissions() RETURNS TABLE (space_id uuid, permission text) {_DEFINER} AS $$
  WITH me AS (
    SELECT app_current_org() AS org, app_current_user() AS uid, coalesce(current_setting('app.role', true), '') AS role
  ),
  raw AS (
    SELECT s.id AS space_id, 'CONTRIBUTE' AS permission FROM knowledge_spaces s, me
      WHERE s.org_id = me.org AND s.kind = 'PERSONAL' AND s.owner_user_id = me.uid
    UNION ALL
    SELECT s.id, 'CONTRIBUTE' FROM knowledge_spaces s, me
      WHERE s.org_id = me.org AND s.kind = 'ORG' AND me.role = 'OWNER'
    UNION ALL
    SELECT g.space_id, g.permission FROM space_grants g, me
      WHERE g.org_id = me.org AND g.principal_type = 'USER' AND g.principal_id = me.uid
        AND (g.expires_at IS NULL OR g.expires_at > now())
    UNION ALL
    SELECT g.space_id, g.permission FROM space_grants g JOIN group_members gm ON gm.group_id = g.principal_id, me
      WHERE g.org_id = me.org AND g.principal_type = 'GROUP' AND gm.user_id = me.uid
        AND (g.expires_at IS NULL OR g.expires_at > now())
  )
  SELECT space_id, CASE WHEN bool_or(permission = 'CONTRIBUTE') THEN 'CONTRIBUTE' ELSE 'READ' END
  FROM raw GROUP BY space_id
$$"""

READABLE = f"""
CREATE FUNCTION app_readable_space_ids() RETURNS uuid[] {_DEFINER} AS $$
  SELECT coalesce(array_agg(space_id), '{{}}') FROM app_space_permissions()
$$"""

WRITABLE = f"""
CREATE FUNCTION app_writable_space_ids() RETURNS uuid[] {_DEFINER} AS $$
  SELECT coalesce(array_agg(space_id), '{{}}') FROM app_space_permissions() WHERE permission = 'CONTRIBUTE'
$$"""

_ORG = "org_id = app_current_org()"
_IS_OWNER = "current_setting('app.role', true) = 'OWNER'"
